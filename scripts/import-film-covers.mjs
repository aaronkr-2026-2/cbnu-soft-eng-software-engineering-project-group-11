import { normalizeFilmCover } from './normalize-film-covers.mjs';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const manifest = JSON.parse(readFileSync(resolve(root, 'scripts/film-cover-manifest.json'), 'utf8'));
const seen = new Set();
const assets = [], rows = [];
for (const sheet of manifest.sheets) {
 const digest = createHash('sha256').update(readFileSync(resolve(root, sheet.path))).digest('hex');
 if (digest !== sheet.sha256) throw new Error('Source checksum mismatch: ' + sheet.path);
}
for (const film of manifest.films) {
 if (seen.has(film.id) || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(film.id)) throw new Error('Invalid/duplicate ID: ' + film.id);
 seen.add(film.id);
 const brandFolder = film.brand.toLowerCase().replace(/[^a-z0-9]+/g, '-');
 const filename = film.id.slice(brandFolder.length + 1) + '.png';
 const relative = `assets/films/${brandFolder}/${filename}`;
 const target = resolve(root, relative); mkdirSync(dirname(target), { recursive: true });
 const [x,y,width,height] = film.crop;
 if (![x,y,width,height].every(Number.isSafeInteger) || x<0 || y<0 || width<=0 || height<=0) throw new Error('Invalid crop: '+film.id);
 execFileSync('sips', ['-c',String(height),String(width),'--cropOffset',String(y),String(x),resolve(root,manifest.sheets[film.sheet].path),'--out',target],{stdio:'ignore'});
 normalizeFilmCover(target);
 assets.push(`  '${film.id}': require('../../../../${relative}'),`);
 if (!film.existing) rows.push(`  ${JSON.stringify([film.id,film.brand,film.name,film.iso,film.type,film.process,film.formats,film.status??null,film.aliases??[]])},`);
}
writeFileSync(resolve(root,'src/features/films/data/additionalFilmAssets.ts'),`import type { ImageSourcePropType } from 'react-native';\n\n// Generated from scripts/film-cover-manifest.json; source sheets are not runtime imports.\nexport const ADDITIONAL_FILM_ASSETS: Readonly<Record<string, ImageSourcePropType>> = {\n${assets.join('\n')}\n};\n`);
writeFileSync(resolve(root,'src/features/films/data/additionalCatalog.ts'),`import type { Film } from '../../../types/models';\n\n// Generated by scripts/import-film-covers.mjs. Keep existing catalog IDs stable.\ntype Definition = [string, string, string, number, Film['type'], string, NonNullable<Film['formats']>, Film['status'] | null, string[]];\nconst definitions: Definition[] = [\n${rows.join('\n')}\n];\nexport const additionalFilms: Film[] = definitions.map(([id, brand, name, iso, type, process, formats, status, aliases]) => ({\n  id, brand, name, iso, type, process, formats, format: formats[0],\n  ...(status ? { status } : {}), aliases, imageKey: id, source: 'builtin', isCustom: false,\n}));\n`);
console.log(`Imported ${rows.length} films and ${assets.length} local covers; preserved ${manifest.sheets.length} source sheets.`);
